#!/usr/bin/env python
"""eur_9a_synthetic_test.py -- end-to-end test of the EUR_9A notebook on SYNTHETIC EDF files (build container only;
never on Kaggle, never on real data).

World (under --root):
  physionet/  a fake PhysioNet CHB-MIT tree (the 23 thesis cases, 2 files of 4 min each + chb12_27-29 without FZ-CZ +
              one 'gap' file each for chb11 and chb21) with SHA256SUMS.txt, served by file:// URLs, so the inventory,
              the download of absent / corrupted files and the hashing use the real code path
  input/      fake Kaggle inputs: the raw copy (gap files ABSENT, chb05_01.edf CORRUPTED -> both from 'PhysioNet');
              v9-x3-fold1/3 = the EARLIER .npz built by the record code on the earlier file set
  repo/       a copy of src/ with data/summaries = the fake PhysioNet summaries, data/processed/*_stats.json from the
              record statistics (seizure map), random GAE v2 checkpoints in the record's format, and the record result
              files (p3c_freeze, e23, e22, calibration k) GENERATED by r2_r1's R1.0 path on the earlier data
Every case has one 40 s seizure except chb23 (seizure-free).
Checks
  P1  EUR_9A notebook: every gate PASS (G-raw, G-data, G-stats0, G-feat0, G-worker x2, R1.0-dev, R1.0-test, G-k, PROJ,
      G-struct); rows complete in r13/lf and r13/lf_krec; no .npz and no EDF in the output folder
  P2  (non-circular) chb23 has no seizure, so no window is skipped either way: its label-free statistics EQUAL the
      committed record statistics exactly; every case with a seizure has different statistics
  P3  the label-free .npz of chb23 equals its earlier .npz (adj, bp5, f7 exactly; same statistics, same builder)
  A   src/eur_9a_aggregate.py on that output: A1 PASS, T9A.md written (A0 is reported only: synthetic record)
  NEG1 a committed stats.json of the smoke case changed by 0.1 % -> STOP at G-stats0 (before R1.0 and the build)
  NEG2 is_buffer flipped in one window of an earlier .npz of a test case (is_buffer does not enter the scoring, so R1.0
       passes) -> STOP at G-struct
  NEG3 an edited module -> the notebook stops before it starts (sha256 assert)
  python src/eur_9a_synthetic_test.py [--root DIR]
"""
import argparse
import json
import os
import shutil
import subprocess
import sys
import time
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
import r2_synthetic_test as RS          # noqa: E402  (EDF writer, summary text)
import r2_r1_synthetic_test as RR       # noqa: E402  (notebook runner, subprocess helper)

DEV = ["chb01", "chb02", "chb04", "chb05", "chb07", "chb08", "chb09", "chb12", "chb19", "chb20", "chb21", "chb23",
       "chb10", "chb11", "chb22"]
TEST = ["chb03", "chb06", "chb13", "chb14", "chb15", "chb16", "chb17", "chb18"]
CASES = DEV + TEST
MIN_PER_FILE = 4
SEIZURE_FREE = "chb23"
GAP = {"chb11": ["chb11_03.edf"], "chb21": ["chb21_03.edf"]}
CORRUPT = "chb05_01.edf"
SMOKE = "chb08"


def files_of(case, i):
    sz = [] if case == SEIZURE_FREE else [(100 + 3 * (i % 5), 140 + 3 * (i % 5))]
    fl = [(f"{case}_01.edf", MIN_PER_FILE, [], (20, 23) if case == "chb17" else None),
          (f"{case}_02.edf", MIN_PER_FILE, sz, None)]
    fl += [(f, MIN_PER_FILE, [], None) for f in GAP.get(case, [])]
    if case == "chb12":
        fl += [(f"chb12_{k}.edf", 3, [], None) for k in (27, 28, 29)]
    return fl


def build_world(root):
    if root.exists():
        shutil.rmtree(root)
    phys = root / "physionet" / "chbmit"
    raw = root / "input" / "combined-siena-scalp-and-chb-mit-eeg-datasets" / "chbmit"
    lap = root / "laptop"
    repo = root / "repo"
    t = time.time()
    seed = 0
    for i, c in enumerate(CASES):
        d = phys / c
        d.mkdir(parents=True)
        fl = files_of(c, i)
        for f, m, sz, flat in fl:
            seed += 1
            RS.write_chb_edf(d / f, m, sz, flat, seed, missing="FZ-CZ" if f.startswith("chb12_2") else None)
        (d / f"{c}-summary.txt").write_text(RS.chb_summary(c, fl))
    lines = [f"{RS.sha(p)} {p.relative_to(phys).as_posix()}" for p in sorted(phys.rglob("*")) if p.is_file()]
    (phys / "SHA256SUMS.txt").write_text("\n".join(lines) + "\n")
    gap = {f for fs in GAP.values() for f in fs}
    for p in sorted(phys.rglob("*")):
        if p.is_file() and p.name != "SHA256SUMS.txt" and p.name not in gap:
            for dst in (raw / p.relative_to(phys), lap / p.relative_to(phys)):
                dst.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(p, dst)
    c = next(raw.rglob(CORRUPT))
    b = bytearray(c.read_bytes())
    b[-100] ^= 0xFF
    c.write_bytes(bytes(b))
    shutil.copytree(ROOT / "src", repo / "src", ignore=shutil.ignore_patterns("__pycache__"))
    for rel in ("results/v9_x3/fold_manifests.json", "results/p3c_freeze/freeze.json", "results/p3_levers/calibration.json"):
        (repo / rel).parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(ROOT / rel, repo / rel)
    (repo / "data" / "summaries").mkdir(parents=True)
    (repo / "data" / "processed").mkdir(parents=True)
    for c in CASES:
        shutil.copyfile(phys / c / f"{c}-summary.txt", repo / "data" / "summaries" / f"{c}-summary.txt")
    print(f"world: {len(CASES)} cases of EDF written ({time.time() - t:.0f} s)", flush=True)
    return phys, raw, lap, repo


RECORD = r'''
# the "record" of the synthetic world: statistics with the seizure map + the record builder on the earlier copy
import json, sys
from pathlib import Path
from multiprocessing import Pool
repo, lap, out1, out3 = map(Path, sys.argv[1:5])
cases = sys.argv[5].split(",")

def one(a):
    i, case = a
    for p in ("src", "src/dataprep", "src/retrain", "src/phaseB", "src/phaseC"):
        sys.path.insert(0, str(repo / p))
    import preprocessing as P, continuous_eval as CE, c1b_build_trainset as C1B
    CE.DATASET_DIR = lap
    smap = P.parse_summary(repo / "data" / "summaries" / f"{case}-summary.txt")
    m, s = P.compute_subject_stats(case, lap, smap)
    thr = P.ARTIFACT_SD_MULTIPLIER * s
    ni, nc, nr = P.count_windows(case, lap, smap, thr)
    st = {"subject_id": case, "n_interictal": ni, "n_ictal": nc, "n_rejected": nr, "ratio": round(ni / max(nc, 1), 1),
          "ch_mean_uV": (m * 1e6).tolist(), "ch_std_uV": (s * 1e6).tolist(), "artifact_thresh_uV": (thr * 1e6).tolist()}
    (repo / "data" / "processed" / f"{case}_stats.json").write_text(json.dumps(st, indent=2))
    C1B.build(case, out_dir=out1 if i % 2 == 0 else out3, allow_test=True)
    return case

if __name__ == "__main__":
    with Pool(4) as pool:
        for c in pool.imap_unordered(one, list(enumerate(cases))):
            print("record built", c, flush=True)
'''

