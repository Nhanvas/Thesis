def env_for(root, repo, tag):
    return dict(EUR_TEST_REPO=str(repo), EUR_TEST_INPUT=str(root / "input"), EUR_TEST_WORK=str(root / f"work_{tag}"),
                EUR_TEST_SCRATCH=str(root / f"scratch_{tag}"), R2_PHYSIONET_CHBMIT=f"file://{root}/physionet/chbmit/",
                R2_TEST_EARLIER_MISSING=json.dumps(GAP), EUR_WORKERS="4", EUR9A_TEST_SMOKE_CASE=SMOKE,
                PYTHONPATH="")


def notebook(root, repo):
    env = dict(os.environ, EUR_NB_OUTDIR=str(root / "notebooks"))
    p = subprocess.run([sys.executable, str(repo / "src" / "eur_make_notebooks.py"), "--only", "EUR_9A"], env=env,
                       capture_output=True, text=True)
    assert p.returncode == 0, p.stderr[-2000:]
    print(p.stdout.strip()[-300:])
    return root / "notebooks" / "EUR_9A.ipynb"


def clone_repo(root, repo, name):
    cp = root / name
    if cp.exists():
        shutil.rmtree(cp)
    shutil.copytree(repo, cp, ignore=shutil.ignore_patterns("__pycache__"))
    return cp


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default="/tmp/eur_9a_synth")
    a = ap.parse_args()
    t0 = time.time()
    root = Path(a.root)
    phys, raw, lap, repo = build_world(root)
    f1, f3 = root / "input" / "v9-x3-fold1" / "fold1", root / "input" / "v9-x3-fold3" / "fold3"
    f1.mkdir(parents=True)
    f3.mkdir(parents=True)
    (root / "record.py").write_text(RECORD)
    (root / "models.py").write_text(MODELS)
    (root / "record_gen.py").write_text(RECORD_GEN)
    (root / "runner.py").write_text(RR.RUNNER)
    t = time.time()
    RR.run(root / "record.py", {}, [repo, lap / "", f1, f3, ",".join(CASES)])
    print(f"record features built ({time.time() - t:.0f} s)", flush=True)
    RR.run(root / "models.py", {}, [repo, f1, f3, root / "tmp_models"])
    genv = dict(THESIS_REPO=str(repo), R2_WORK=str(root / "work_gen"), R2_INPUT=str(root / "input"),
                R2_SCRATCH=str(root / "scratch_gen"), R2_TEST="1", R1_SRC=str(repo / "src"), OMP_NUM_THREADS="1")
    print(RR.run(root / "record_gen.py", genv).strip().splitlines()[-1])
    nb = notebook(root, repo)

    # ---- P1: the notebook end to end
    t = time.time()
    out = RR.run(root / "runner.py", env_for(root, repo, "ok"), [nb])
    print(out.strip()[-1500:])
    w = root / "work_ok" / "eureka" / "9a"
    gates = json.loads((w / "gates.json").read_text())
    names = {g["gate"]: g["status"] for g in gates}
    need = ("G-raw", "G-data", "G-stats0", "G-feat0", "G-worker[smoke]", "R1.0-dev", "R1.0-test", "G-k", "PROJ",
            "G-struct", "G-worker[build]")
    assert all(names.get(n) == "PASS" for n in need), names
    import pandas as pd
    for lab in ("lf", "lf_krec"):
        d = pd.read_csv(w / "r13" / lab / "per_subject.csv")
        assert len(d) == len(CASES) * 4 * 4 * 3 and d.subject.nunique() == len(CASES), (lab, len(d))
    bad = [p for p in w.rglob("*") if p.suffix.lower() in (".npz", ".edf")]
    assert not bad, bad
    inv = pd.read_csv(w / "inventory" / "inventory.csv")
    src = dict(zip(inv.file, inv.source))
    assert src["chb11_03.edf"].startswith("physionet") and src[CORRUPT].startswith("physionet"), src
    print(f"P1 PASS: every gate, rows complete, gap and corrupted files from 'PhysioNet', no .npz / EDF in the output "
          f"({time.time() - t:.0f} s)")

    # ---- P2 / P3 (non-circular)
    rec = json.loads((repo / "data" / "processed" / f"{SEIZURE_FREE}_stats.json").read_text())
    lf = json.loads((w / "stats_lf" / f"{SEIZURE_FREE}_stats.json").read_text())
    assert rec["ch_mean_uV"] == lf["ch_mean_uV"] and rec["ch_std_uV"] == lf["ch_std_uV"], "P2 seizure-free case"
    diff = [c for c in CASES if c != SEIZURE_FREE and json.loads((repo / "data" / "processed" / f"{c}_stats.json")
            .read_text())["ch_std_uV"] == json.loads((w / "stats_lf" / f"{c}_stats.json").read_text())["ch_std_uV"]]
    assert not diff, f"P2: statistics unchanged although the case has a seizure: {diff}"
    zl = np.load(root / "scratch_ok" / "r1_views" / "new" / f"{SEIZURE_FREE}.npz", allow_pickle=True)
    ze = np.load(next((root / "input").rglob(f"{SEIZURE_FREE}.npz")), allow_pickle=True)
    for k in ("adj", "bp5", "f7", "is_flag5sd"):
        assert np.array_equal(zl[k], ze[k], equal_nan=k != "is_flag5sd"), k
    print("P2 PASS: seizure-free chb23 -> label-free statistics = record statistics exactly; every other case differs")
    print("P3 PASS: chb23's label-free .npz = its earlier .npz (adj, bp5, f7, flags)")

    # ---- A: aggregate
    aenv = dict(THESIS_REPO=str(repo), R2_TEST="1")
    o = RR.run(repo / "src" / "eur_9a_aggregate.py", aenv, ["--run", w])
    assert "A1 PASS" in o and (w / "aggregate" / "T9A.md").exists(), o[-1500:]
    print(o.strip().splitlines()[-1])
    print("A PASS: aggregate A1 and T9A.md")

    # ---- NEG1: changed committed statistics -> STOP at G-stats0
    cp = clone_repo(root, repo, "repo_neg1")
    p = cp / "data" / "processed" / f"{SMOKE}_stats.json"
    st = json.loads(p.read_text())
    st["ch_std_uV"][0] *= 1.001
    p.write_text(json.dumps(st, indent=2))
    RR.run(root / "runner.py", env_for(root, cp, "neg1"), [nb], expect_fail="G-stats0 FAIL")
    g = {x["gate"] for x in json.loads((root / "work_neg1" / "eureka" / "9a" / "gates.json").read_text())}
    assert "R1.0-dev" not in g and "G-struct" not in g, g
    print("NEG1 PASS: a changed committed statistics file stops at G-stats0, before R1.0 and the build")

    # ---- NEG2: is_buffer flipped in an earlier .npz of a test case -> R1.0 PASS, STOP at G-struct
    inp2 = root / "input_neg2"
    if inp2.exists():
        shutil.rmtree(inp2)
    shutil.copytree(root / "input", inp2, symlinks=False)
    q = next(inp2.rglob("chb03.npz"))
    z = dict(np.load(q, allow_pickle=True))
    z["is_buffer"] = np.array(z["is_buffer"], copy=True)
    z["is_buffer"][5] = ~z["is_buffer"][5]
    np.savez(q, **z)
    e2 = env_for(root, repo, "neg2")
    e2["EUR_TEST_INPUT"] = str(inp2)
    RR.run(root / "runner.py", e2, [nb], expect_fail="G-struct FAIL")
    g = {x["gate"]: x["status"] for x in json.loads((root / "work_neg2" / "eureka" / "9a" / "gates.json").read_text())}
    assert g.get("R1.0-dev") == "PASS" and g.get("R1.0-test") == "PASS" and g.get("G-struct") == "FAIL", g
    print("NEG2 PASS: an earlier .npz whose is_buffer differs passes R1.0 (not scored) and stops at G-struct")

    # ---- NEG3: edited module -> stop before anything runs
    cp = clone_repo(root, repo, "repo_neg3")
    with open(cp / "src" / "eur_9a.py", "a") as f:
        f.write("# edited\n")
    RR.run(root / "runner.py", env_for(root, cp, "neg3"), [nb], expect_fail="modules differ")
    print("NEG3 PASS: an edited module stops the notebook before it starts")
    print(f"ALL PASS in {time.time() - t0:.0f} s")


if __name__ == "__main__":
    main()
