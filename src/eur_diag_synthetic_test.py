#!/usr/bin/env python
"""eur_diag_synthetic_test.py -- end-to-end test of the EUR_DIAG notebook on SYNTHETIC EDF files (build container only;
never on Kaggle, never on real data). The world is the EUR_9A test world (src/eur_9a_synthetic_test.py: 23 CHB-MIT-like
cases, a fake PhysioNet with SHA256SUMS served by file://, a corrupted and absent files on the fake Kaggle copy, earlier
.npz and record rows generated by the record code) with: short seizures (12-16 s) in the test cases and one development
case, and the external sets: chb24 (2 files, its summary lists only the file with a seizure) and Siena PN00 (2 files) and
PN01 (1 file) as a fake Siena PhysioNet tree; their label-free .npz built by r2_core's R0.4 path (x1_external) and their
record rows (results/x1_external) generated by r2_r1's R1.0 path.
Checks
  P1  EUR_DIAG: every gate PASS (G-raw, G-data, R1.0-dev / -test, GE, G-k, G-ev, G-s0, G-extstats, G-worker); D1 rows for
      every short seizure (= the record's short_n per case) x 4 shifts x 4 seeds; EV events for every case; no .npz / EDF in the output
  P2  (non-circular) the shift-0 decision rebuilt from the raw EDF equals the decision on the STORED V5 smoothed scalar
      (peak over the seizure vs the patient's threshold) for every seizure-seed not within 0.02 of the threshold
  P3  EV: the seizure / false-alarm labels add up to the r10 counts' direction (at least one seizure event per case with
      tp > 0); every feature column finite for events of >= 1 window
  NEG1 a Siena EDF corrupted on the fake Kaggle copy AND on the fake PhysioNet download -> STOP R0.1 (sha256)
  NEG2 an edited module -> STOP before anything runs
  python src/eur_diag_synthetic_test.py [--root DIR]
"""
import argparse
import json
import os
import shutil
import subprocess
import sys
import time
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
import r2_synthetic_test as RS          # noqa: E402
import r2_r1_synthetic_test as RR       # noqa: E402
import eur_9a_synthetic_test as T9      # noqa: E402

SHORT = set(T9.TEST) | {"chb10"}
EXT_SIENA = {"PN00": [("PN00-1.edf", 5, (100, 114)), ("PN00-2.edf", 4, (60, 100))], "PN01": [("PN01-1.edf", 5, (120, 133))]}
CHB24 = [("chb24_01.edf", 4, [(90, 104)], None), ("chb24_02.edf", 4, [], None)]


_FILES_9A = T9.files_of


def files_of(case, i):
    fl = _FILES_9A(case, i)
    if case in SHORT:
        on = 100 + 3 * (i % 5)
        fl = [(f, m, [(on, on + 12 + 2 * (i % 3))] if sz else [], flat) for f, m, sz, flat in fl]
    return fl


def build_world(root):
    T9.files_of = files_of                       # short seizures in the 9A world
    phys, raw, lap, repo = T9.build_world(root)
    # chb24 (CHB-MIT tree) and Siena
    d = phys / "chb24"
    d.mkdir()
    seed = 900
    for f, m, sz, flat in CHB24:
        seed += 1
        RS.write_chb_edf(d / f, m, sz, flat, seed)
    (d / "chb24-summary.txt").write_text(RS.chb_summary("chb24", CHB24))
    lines = [f"{RS.sha(p)} {p.relative_to(phys).as_posix()}" for p in sorted(phys.rglob("*"))
             if p.is_file() and p.name != "SHA256SUMS.txt"]
    (phys / "SHA256SUMS.txt").write_text("\n".join(lines) + "\n")
    sp = root / "physionet" / "siena"
    for c, fl in EXT_SIENA.items():
        (sp / c).mkdir(parents=True)
        for f, m, s in fl:
            seed += 1
            RS.write_siena_edf(sp / c / f, m, s, seed)
        (sp / c / f"Seizures-list-{c}.txt").write_text(RS.siena_list(c, fl))
    lines = [f"{RS.sha(p)} {p.relative_to(sp).as_posix()}" for p in sorted(sp.rglob("*")) if p.is_file()]
    (sp / "SHA256SUMS.txt").write_text("\n".join(lines) + "\n")
    kag = root / "input" / "combined-siena-scalp-and-chb-mit-eeg-datasets"
    for src, sub in ((phys / "chb24", "chbmit/chb24"), (sp, "siena")):
        for p in sorted(src.rglob("*")):
            if p.is_file() and p.name != "SHA256SUMS.txt":
                q = kag / sub / p.relative_to(src)
                q.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(p, q)
    x1 = repo / "results" / "x1_external"
    x1.mkdir(parents=True, exist_ok=True)
    for c in ["chb24"] + list(EXT_SIENA):
        (x1 / f"rows_{c}.csv").write_text("placeholder\n")
    return phys, raw, lap, repo, sp


EXT_BUILD = r'''
# external label-free features by r2_core's R0.4 path (x1_external.build_subject), saved as thesis-r2-external-features
import json, sys
from pathlib import Path
import numpy as np
repo, complete, out = map(Path, sys.argv[1:4])
for p in ("src", "src/dataprep", "src/retrain", "src/phaseB", "src/phaseC"):
    sys.path.insert(0, str(repo / p))
import r2_core as R0
if __name__ == "__main__":
    out.mkdir(parents=True, exist_ok=True)
    for c in sys.argv[4].split(","):
        z, meta = R0.ext_job(c, complete, 2, out / f"_{c}.log")
        np.savez(out / f"{c}_lf.npz", **z, meta=json.dumps(meta, default=str))
        print("ext built", c, flush=True)
'''

RECORD_GEN_EXT = T9.RECORD_GEN.replace(
    'A.build_views(A.DEV, A.TEST, [])\n    cs = [(c, "earlier") for c in A.DEV + A.TEST]',
    'A.build_views(A.DEV, A.TEST, A.EXT)\n    cs = [(c, "earlier") for c in A.DEV + A.TEST] + [(c, "ext") for c in A.EXT]').replace(
    '    print("record generated: k", k)',
    '    for c in A.EXT:\n'
    '        pd.DataFrame(s[c]["x1_rows"]).to_csv(REPO / f"results/x1_external/rows_{c}.csv", index=False)\n'
    '        pd.DataFrame(s[c]["x1_errs"]).to_csv(REPO / f"results/x1_external/errors_{c}.csv", index=False)\n'
    '    print("record generated: k", k, "ext", A.EXT)')


def env_for(root, repo, tag):
    e = T9.env_for(root, repo, tag)
    e["R2_PHYSIONET_SIENA"] = f"file://{root}/physionet/siena/"
    return e


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default="/tmp/eur_diag_synth")
    a = ap.parse_args()
    t0 = time.time()
    root = Path(a.root)
    phys, raw, lap, repo, sp = build_world(root)
    f1, f3 = root / "input" / "v9-x3-fold1" / "fold1", root / "input" / "v9-x3-fold3" / "fold3"
    f1.mkdir(parents=True)
    f3.mkdir(parents=True)
    for n, txt in (("record.py", T9.RECORD), ("models.py", T9.MODELS), ("record_gen.py", RECORD_GEN_EXT),
                   ("runner.py", RR.RUNNER), ("ext_build.py", EXT_BUILD)):
        (root / n).write_text(txt)
    RR.run(root / "record.py", {}, [repo, lap / "", f1, f3, ",".join(T9.CASES)])
    comp = root / "complete_view"
    (comp / "chbmit").mkdir(parents=True)
    shutil.copytree(phys / "chb24", comp / "chbmit" / "chb24")
    shutil.copytree(sp, comp / "siena")
    dx = root / "input" / "thesis-r2-external-features" / "thesis-r2-external-features"
    print(RR.run(root / "ext_build.py", dict(R2_TEST="1", THESIS_REPO=str(repo)),
                 [repo, comp, dx, ",".join(["chb24"] + list(EXT_SIENA))]).strip().splitlines()[-1])
    for p in dx.glob("_*.log"):
        p.unlink()
    RR.run(root / "models.py", {}, [repo, f1, f3, root / "tmp_models"])
    genv = dict(THESIS_REPO=str(repo), R2_WORK=str(root / "work_gen"), R2_INPUT=str(root / "input"),
                R2_SCRATCH=str(root / "scratch_gen"), R2_TEST="1", R1_SRC=str(repo / "src"), OMP_NUM_THREADS="1")
    print(RR.run(root / "record_gen.py", genv).strip().splitlines()[-1])
    env = dict(os.environ, EUR_NB_OUTDIR=str(root / "notebooks"))
    p = subprocess.run([sys.executable, str(repo / "src" / "eur_make_notebooks.py"), "--only", "EUR_DIAG"], env=env,
                       capture_output=True, text=True)
    assert p.returncode == 0, p.stderr[-2000:]
    nb = root / "notebooks" / "EUR_DIAG.ipynb"

    # ---- P1
    t = time.time()
    out = RR.run(root / "runner.py", env_for(root, repo, "ok"), [nb])
    print(out.strip()[-2500:])
    w = root / "work_ok" / "eureka" / "diag"
    gates = {g["gate"]: g["status"] for g in json.loads((w / "gates.json").read_text())}
    need = ("G-raw", "G-data", "R1.0-dev", "R1.0-test", "GE", "G-k", "G-ev", "G-s0", "G-extstats", "G-worker")
    assert all(gates.get(n) == "PASS" for n in need), gates
    import pandas as pd
    D = pd.read_csv(w / "d1_rows.csv")
    n_short = D.groupby(["subject", "file", "onset_s"]).ngroups
    assert len(D) == n_short * 4 * 4, (len(D), n_short)
    rr = pd.concat([pd.read_csv(w / "r10" / f) for f in ("dev_per_subject.csv", "test_run_budget.csv")])
    want = rr[(rr.budget == "L2f") & (rr.stage == "detector") & (rr.seed == "clean_seed42")].set_index("subject").short_n
    got = D[D["set"].isin(["development", "test"])].groupby("subject")[["file", "onset_s"]].apply(
        lambda g: g.drop_duplicates().shape[0])
    assert all(int(got.get(s_, 0)) == int(v) for s_, v in want.items()), (got.to_dict(), want[want > 0].to_dict())
    assert {"chb24", "PN00"} <= set(D.subject), sorted(set(D.subject))
    E = pd.read_csv(w / "ev_events.csv")
    assert E.subject.nunique() == len(T9.CASES) + 3, E.subject.nunique()
    bad = [q for q in w.rglob("*") if q.suffix.lower() in (".npz", ".edf")]
    assert not bad, bad
    print(f"P1 PASS: every gate, D1 {n_short} short seizures x 4 shifts x 4 seeds, EV events for every case, no .npz / "
          f"EDF in the output ({time.time() - t:.0f} s)")

    # ---- P2: the raw-path decision at shift 0 = the decision on the stored V5 scalar (where not within the G-s0 band)
    s0 = D[D.shift_s == 0].copy()
    far = (s0.peak_record_s0 - s0.thr).abs() > 0.02
    mism = s0[far & ((s0.peak_record_s0 > s0.thr) != s0.within)]
    assert not len(mism), mism.head()
    print(f"P2 PASS: shift-0 within-budget decision from the raw EDF = the stored V5 scalar's for {int(far.sum())} of "
          f"{len(s0)} seizure-seeds (the rest within 0.02 of the threshold)")

    # ---- P3
    one = E[E.end_s - E.start_s >= 4]
    cols = [c for c in E.columns if c.endswith("_med")] + ["line_length_max", "evo_dfreq", "evo_amp", "duration"]
    assert np.isfinite(one[cols].values.astype(float)).all(), "non-finite EV features"
    r10c = pd.concat([pd.read_csv(w / "r10" / f) for f in ("dev_per_subject.csv", "test_run_budget.csv")])
    tp = r10c[(r10c.budget == "L2f") & (r10c.stage == "cpd")].groupby("subject").tp.sum()
    lab = E[E.label == "seizure"].groupby("subject").size()
    miss = [s for s, v in tp.items() if v > 0 and s not in lab.index]
    assert not miss, miss
    print("P3 PASS: EV features finite; every case with detected seizures has seizure events")
    assert (w / "D1.md").exists() and (w / "EV.md").exists()

    # ---- NEG1: a Siena file corrupted on Kaggle AND on 'PhysioNet' -> STOP
    root_neg = root / "neg1"
    if root_neg.exists():
        shutil.rmtree(root_neg)
    shutil.copytree(root / "physionet", root_neg / "physionet")
    q = root_neg / "physionet" / "siena" / "PN01" / "PN01-1.edf"
    b = bytearray(q.read_bytes())
    b[-50] ^= 0xFF
    q.write_bytes(bytes(b))
    kq = next((root / "input").rglob("PN01-1.edf"))
    orig = kq.read_bytes()
    kq.write_bytes(bytes(b))
    try:
        e = env_for(root, repo, "neg1")
        e["R2_PHYSIONET_SIENA"] = f"file://{root_neg}/physionet/siena/"
        RR.run(root / "runner.py", e, [nb], expect_fail="sha256")
    finally:
        kq.write_bytes(orig)
    print("NEG1 PASS: a file that matches no PhysioNet checksum stops the run")

    # ---- NEG2
    cp = T9.clone_repo(root, repo, "repo_neg2")
    with open(cp / "src" / "eur_diag.py", "a") as f:
        f.write("# edited\n")
    RR.run(root / "runner.py", env_for(root, cp, "neg2"), [nb], expect_fail="modules differ")
    print("NEG2 PASS: an edited module stops the notebook before it starts")
    print(f"ALL PASS in {time.time() - t0:.0f} s")


if __name__ == "__main__":
    main()
