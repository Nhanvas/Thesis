def ci_has0(r):
    return r["lo"] <= 0 <= r["hi"]


def plant_one_dir(adj, rng, share=0.08):
    """what FA14_DIAG found in the real windows: in a share of the windows with edges, the pair at the top-k cut (the
    smallest kept value) is kept in one direction only (the other entry set to 0; direction at random). In place."""
    nz = np.flatnonzero((adj > 0).any((1, 2)))
    for w in rng.choice(nz, size=max(1, int(round(share * len(nz)))), replace=False):
        a = adj[w]
        iu = np.triu_indices(18, 1)
        v = a[iu]
        m = v[v > 0].min()
        k = np.flatnonzero(v == m)[0]
        i, j = iu[0][k], iu[1][k]
        if rng.random() < 0.5:
            i, j = j, i
        a[j, i] = 0.0
    return adj


