def part_n():
    os.environ.setdefault("FA14_WORK", "/tmp/fa14_n")
    import torch
    import fa14_mech as M
    from r2_r1_synthetic_test import make_case
    C, F = M.C, M.F
    torch.manual_seed(3)
    model = F.build("gae").eval()
    z, _ = make_case("chb03", 5)
    n = len(z["is_ictal"])
    ok = ~z["is_signal_loss"]
    ctx = dict(s="chb03", z=z, idx=np.flatnonzero(ok), n=n, ok=ok)
    meta = dict(add_mean=[0.0] * 7, add_std=[1.0] * 7, clip=4.0)
    D1 = F.encode_D("gae", model, meta, ctx)
    D2 = C.d_from_Z(M.encode_Z(model, meta, ctx, prop=None))
    assert np.array_equal(D1, D2)
    print("N1 encode_Z(window graph) = f1_core.encode_D bit for bit -> PASS")
    zc = dict(z)
    adj = np.array(z["adj"], copy=True)
    adj[:] = adj[0]
    zc["adj"] = adj
    ctx2 = dict(ctx, z=zc)
    G = M.fixed_graph(M.valid_adj(ctx2))
    assert np.array_equal(G, M.valid_adj(ctx2)[0])
    Zb = M.encode_Z(model, meta, ctx2, prop=None)
    Zf = M.encode_Z(model, meta, ctx2, prop=G)
    assert np.array_equal(Zb, Zf)
    print("N2 I-fix on a case whose graph is the same in every window = the base arm bit for bit -> PASS")
    X30, *_ = C.node_input(z, ctx["idx"], meta)
    with torch.no_grad():
        x = torch.tensor(X30.reshape(-1, 30))
        h = torch.relu(model.encoder.conv1.lin(x) + model.encoder.conv1.bias)
        want = (model.encoder.conv2.lin(h) + model.encoder.conv2.bias).view(-1, 18, 16).numpy()
    got = M.encode_Z(model, meta, ctx, prop="self")
    assert np.allclose(got, want, atol=1e-5), np.abs(got - want).max()
    print(f"N3 I-self = lin -> relu -> lin (GCN self weight 1), max |diff| {np.abs(got - want).max():.1e} -> PASS")
    from torch_geometric.nn.conv.gcn_conv import gcn_norm
    a = M.valid_adj(ctx)[:64]
    A = torch.tensor(a)
    b, i, j = A.nonzero(as_tuple=True)
    ei2, w2 = gcn_norm(torch.stack([b * 18 + i, b * 18 + j]), A[b, i, j], num_nodes=64 * 18, add_self_loops=True)
    s = ei2[0] == ei2[1]
    g = np.zeros(64 * 18); g[ei2[0][s].numpy()] = w2[s].numpy()
    assert np.max(np.abs(g - M.gcn_self_weight(a).ravel())) < 1e-6
    print("N4 self weight 1 / (1 + column sum w) = gcn_norm -> PASS")
    rng = np.random.default_rng(11)
    g5 = np.empty((400, 18, 18), np.float32)
    for w in range(400):
        x = rng.random((18, 18)); x = (x + x.T) / 2; np.fill_diagonal(x, 0)
        g5[w] = M.GC.apply_topk_threshold(x)
    plant_one_dir(g5, rng)
    A = torch.tensor(g5)
    b, i, j = A.nonzero(as_tuple=True)
    ei2, w2 = gcn_norm(torch.stack([b * 18 + i, b * 18 + j]), A[b, i, j], num_nodes=400 * 18, add_self_loops=True)
    s = ei2[0] == ei2[1]
    g = np.zeros(400 * 18); g[ei2[0][s].numpy()] = w2[s].numpy()
    e_col = np.max(np.abs(g - M.gcn_self_weight(g5).ravel()))
    e_row = np.max(np.abs(g - (1.0 / (1.0 + g5.sum(2, dtype=np.float64))).ravel()))
    assert e_col < 1e-6 and e_row > 1e-2, (e_col, e_row)
    G5 = M.fixed_graph(g5)
    assert np.array_equal(G5, G5.T) and (G5 > 0).sum() // 2 >= 30 and np.all(np.diag(G5) == 0)
    h0 = M.GC.apply_topk_threshold((lambda x: (x + x.T) / 2)(rng.random((18, 18))))
    np.fill_diagonal(h0, 0)
    ii, jj = np.argwhere(np.triu(h0 > 0, 1))[0]
    h1 = h0.copy(); h1[jj, ii] = 0.0                                   # message jj -> ii dropped
    J, dd, _ = M.edge_change(np.stack([h0, h1]).astype(np.float32), np.array([1]))
    want = np.zeros(18); want[ii] = 1.0 / (h0[:, ii] > 0).sum()
    assert np.allclose(J[0], want) and np.isclose(dd[0, ii], h0[jj, ii]) and dd[0, jj] == 0, (J[0], dd[0])
    print(f"N5 one-directional pairs (8 % of windows): column-sum self weight = gcn_norm (max |diff| {e_col:.1e}), "
          f"row sum {e_row:.2f} off; fixed_graph symmetric, {int((G5 > 0).sum() // 2)} pairs; edge_change on incoming edges "
          "(hand example) -> PASS")
    print("PART N ALL PASS")


