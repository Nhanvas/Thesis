def part_u():
    os.environ.setdefault("FA14_WORK", "/tmp/fa14_u")
    import fa14_mech as M
    import fa14_aggregate as AG
    rng = np.random.default_rng(7)

    def graphs(n, rho_max=0.8):
        base = rng.random((18, 18)); base = (base + base.T) / 2; np.fill_diagonal(base, 0)
        adj = np.empty((n, 18, 18), np.float32)
        for w in range(n):
            rho = rng.uniform(0, rho_max)
            noise = rng.random((18, 18)); noise = (noise + noise.T) / 2
            a = (1 - rho) * base + rho * noise
            np.fill_diagonal(a, 0)
            adj[w] = M.GC.apply_topk_threshold(a)
        return plant_one_dir(adj, rng)

    def patient(kind, n=3000):
        adj = graphs(n)
        A = rng.normal(0, 1, (n, 18))
        foc = rng.random(n) < 0.08
        ch = rng.integers(0, 18, n)
        A[foc, ch[foc]] = rng.uniform(4, 8, foc.sum())
        s = 0.8 * A + 0.6 * rng.normal(0, 1, (n, 18))
        zm = M.rz_cols(s + 0.5 * rng.normal(0, 1, (n, 18)))
        if kind == "spread":
            rown = adj / np.maximum(adj.sum(2, keepdims=True), 1e-9)
            g = s + 0.6 * np.einsum("wij,wj->wi", rown, s) + 0.5 * rng.normal(0, 1, (n, 18))
        elif kind == "regression":
            g = s + 0.5 * rng.normal(0, 1, (n, 18))
        elif kind == "instability":
            J = np.zeros((n, 18))
            w = np.arange(1, n)
            J[w] = M.edge_change(adj, w)[0]
            g = s + 0.5 * rng.normal(0, 1, (n, 18)) + 1.5 * J
        za = M.rz_cols(g)
        bg = np.ones(n, bool)
        idx = np.arange(n)
        wf = np.zeros(n, int)
        return za, zm, M.rz_cols(A), bg, adj, idx, wf

    def world(kind):
        rows = {k: {} for k in ("in", "inother", "asym", "mlpf", "nb", "slope")}
        for c in CHB:
            za, zm, A, bg, adj, idx, wf = patient(kind)
            h = {r["definition"]: r for r in M.h1_rows(za, zm, A, bg, 4.0, 2.0)}
            rows["in"][c] = h["input"]["dR"]
            rows["inother"][c] = h["input"]["dR"] - h["input"]["dR_other"]
            rows["mlpf"][c] = h["mlpfocal"]["dR"]
            rows["asym"][c] = h["mlpfocal"]["dR"] - h["armfocal"]["dR"]
            nb = M.h1nb_counts(za, zm, A, bg, 4.0, 2.0, "window", adj)
            rows["nb"][c] = nb["nb_armonly"] / nb["n_armonly"] - nb["nb_all"] / nb["n_all"] if nb["n_armonly"] else np.nan
            w = M.consecutive_pairs(idx, wf, bg)
            rows["slope"][c] = M.h2_row(za, zm, A, adj, w)["slope_J"]
        bt = AG.Boot(CHB, b=2000)
        return {k: bt.mean(pd.Series(v)) for k, v in rows.items()}

    t = time.time()
    R1 = world("spread")
    assert R1["inother"]["lo"] > 0 and R1["nb"]["lo"] > 0 and R1["asym"]["lo"] > 0, R1
    assert ci_has0(R1["slope"]), R1["slope"]
    print(f"U-W1 planted spread: input-focal dR - other {R1['inother']['est']:+.3f} [{R1['inother']['lo']:+.3f}, "
          f"{R1['inother']['hi']:+.3f}], neighbour enrichment {R1['nb']['est']:+.3f} [{R1['nb']['lo']:+.3f}, "
          f"{R1['nb']['hi']:+.3f}], asymmetry {R1['asym']['est']:+.3f} [{R1['asym']['lo']:+.3f}, {R1['asym']['hi']:+.3f}]; "
          f"slope_J {R1['slope']['est']:+.3f} contains 0 -> PASS")
    R2 = world("regression")
    assert R2["mlpf"]["lo"] > 0, R2["mlpf"]
    assert ci_has0(R2["inother"]) and ci_has0(R2["asym"]) and ci_has0(R2["nb"]), R2
    print(f"U-W2 regression only: one-sided mlp-focal dR {R2['mlpf']['est']:+.3f} [{R2['mlpf']['lo']:+.3f}, "
          f"{R2['mlpf']['hi']:+.3f}] (selection artifact) while input-focal - other {R2['inother']['est']:+.3f}, "
          f"asymmetry {R2['asym']['est']:+.3f}, neighbour enrichment {R2['nb']['est']:+.3f} all contain 0 -> PASS")
    R3 = world("instability")
    assert R3["slope"]["lo"] > 0 and ci_has0(R3["inother"]) and R3["asym"]["hi"] < 0.05 and R3["nb"]["hi"] < 0.05, R3
    print(f"U-W3 planted instability: slope_J {R3['slope']['est']:+.3f} [{R3['slope']['lo']:+.3f}, "
          f"{R3['slope']['hi']:+.3f}]; input-focal - other {R3['inother']['est']:+.3f} contains 0; the model-based "
          f"asymmetry {R3['asym']['est']:+.3f} [{R3['asym']['lo']:+.3f}, {R3['asym']['hi']:+.3f}] and the neighbour "
          f"enrichment {R3['nb']['est']:+.3f} do not take H1's side (unequal noise moves the swap control the other "
          f"way) -> PASS")
    # W4 dilution
    dp, dn = {}, {}
    for c in CHB:
        n = 900
        fidx = np.repeat([0, 1], n // 2)
        ok = np.ones(n, bool)
        xs_m = rng.uniform(0, 1, n)
        refs = {0: [(400, 440)], 1: [(800, 860)]}
        xs_m[100:110] = 0.995 + 0.004 * rng.random(10)
        xs_m[450 + 200:450 + 215] = 0.995 + 0.004 * rng.random(15)
        xs_g = xs_m.copy()
        xs_g[95:115] -= 0.02
        xs_g[450 + 195:450 + 220] -= 0.02
        a = pd.DataFrame(M.seizure_peaks(xs_g, ok, fidx, refs))
        m = pd.DataFrame(M.seizure_peaks(xs_m, ok, fidx, refs))
        dp[c] = (a.peak - m.peak).mean()
        dn[c] = (a.p_need - m.p_need).mean()
    bt = AG.Boot(CHB, b=2000)
    r4, r4n = bt.mean(pd.Series(dp)), bt.mean(pd.Series(dn))
    assert r4["hi"] < 0 and r4n["lo"] > 0, (r4, r4n)
    print(f"U-W4 planted dilution: d_peak {r4['est']:+.4f} [{r4['lo']:+.4f}, {r4['hi']:+.4f}], d_p_need "
          f"{r4n['est']:+.4f} -> PASS")
    # F3-A identity
    rows = []
    for c in CHB:
        for arm in ("gae", "mlp"):
            n_fa = int(rng.integers(5, 60)); t_fa = float(rng.uniform(100, 3000)) * n_fa / 10
            rows.append(dict(subject=c, arm=arm, n_ev=n_fa + 3, t_ev=t_fa + rng.uniform(300, 900), n_fa=n_fa, t_fa=t_fa))
    g = pd.DataFrame(rows)
    t3 = AG.f3a_terms(g, "gae", "mlp")
    assert t3["identity_error"] < 1e-12, t3
    bb = AG.boot_f3a(AG.Boot(CHB, b=500), g, "gae", "mlp")
    assert all(np.isfinite(v) for v in bb.values()), bb
    print(f"U-F3A identity: log ratio {t3['log_ratio']:+.4f} = {t3['budget']:+.4f} + {t3['seizure_share']:+.4f} + "
          f"{t3['fragmentation']:+.4f} (error {t3['identity_error']:.1e}); bootstrap finite -> PASS")
    # false-alarm rules, hand example (PRE 30 s, POST 60 s)
    refs = {0: [(400, 440)]}
    ev = {0: [(300, 368), (368, 380), (496, 520), (504, 600), (1000, 1100)]}
    fa = M.fa_events(ev, refs)
    assert [e[3] for e in fa] == [True, False, False, True, True], fa
    det_other = {0: [(1040, 1060)]}
    assert M.overlaps(det_other, 0, 1000, 1100) and not M.overlaps(det_other, 0, 300, 368)
    xs = np.zeros(400); xs[262] = 5; xs[260:270] += 1
    fidx = np.zeros(400, int); ok = np.ones(400, bool)
    assert M.peak_window(xs, fidx, 0, 1000, 1100, ok) == 262
    print("U-FA rules: overlap with onset - 30 s / offset + 60 s, cross-model overlap and the event peak as written -> PASS")
    adj = graphs(200)
    G = M.fixed_graph(adj)
    ne = int((G > 0).sum() // 2)
    assert 30 <= ne <= 34 and np.allclose(G, G.T) and np.all(np.diag(G) == 0), ne
    print(f"U-fixed graph: {ne} undirected edges (20 % of 153 = 30, ties kept), symmetric, no self-loop -> PASS")
    print(f"PART U ALL PASS ({time.time() - t:.0f} s)")


