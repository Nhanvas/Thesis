def run(script, env, args=(), expect_fail=None):
    p = subprocess.run([sys.executable, str(script), *map(str, args)], env=dict(os.environ, **env), capture_output=True,
                       text=True)
    tail = p.stdout[-3000:] + "\n" + p.stderr[-4000:]
    if expect_fail is None:
        if p.returncode != 0:
            print(tail)
            raise SystemExit(f"FAILED: {script} {args}")
        return p.stdout
    if p.returncode == 0 or expect_fail not in tail:
        print(tail)
        raise SystemExit(f"expected a STOP containing {expect_fail!r}: {script} {args}")
    return tail


