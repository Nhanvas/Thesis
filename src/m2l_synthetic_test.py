def notebooks(root, repo):
    env = dict(os.environ, M2L_NB_OUTDIR=str(root / "notebooks"))
    p = subprocess.run([sys.executable, str(repo / "src" / "m2l_make_notebooks.py")], env=env, capture_output=True,
                       text=True)
    assert p.returncode == 0, p.stderr[-2000:]
    return root / "notebooks"


def gates(work, tag):
    return {g["gate"]: g["status"] for g in json.loads((work / "m2l" / tag / "gates.json").read_text())}


def copy_out(root, run_tag, repo, tag):
    src = root / f"work_{run_tag}" / "m2l" / tag
    dst = repo / "results" / "m2l" / tag
    if dst.exists():
        shutil.rmtree(dst)
    shutil.copytree(src, dst)
    bad = [p for p in src.rglob("*") if p.suffix.lower() in (".npz", ".edf")]
    assert not bad, bad


def unit_tests(repo):
    sys.path.insert(0, str(repo / "src"))
    import m2l_read as RD
    arms = RD.SELECT
    L = pd.DataFrame(dict(arm=arms, f1=[0.20] * len(arms)))

    def bt(spec):
        rows = []
        for a in arms:
            d_f1, lo, d_s = spec.get(a, (0.0, -0.01, 0.0))
            rows += [dict(arm=a, vs=RD.P0, metric="f1", diff=d_f1, ci_lo=lo, ci_hi=d_f1 + 0.01),
                     dict(arm=a, vs=RD.P0, metric="sens", diff=d_s, ci_lo=d_s - 0.01, ci_hi=d_s + 0.01)]
        return pd.DataFrame(rows)
    assert RD.select_arm(L, bt({}))[0] == RD.P0
    L2 = L.copy(); L2.loc[L2.arm == "B-MCD-N", "f1"] = 0.25
    assert RD.select_arm(L2, bt({"B-MCD-N": (0.05, 0.01, 0.0)}))[0] == "B-MCD-N"
    assert RD.select_arm(L2, bt({"B-MCD-N": (0.05, 0.01, -0.04)}))[0] == RD.P0          # sensitivity guard
    L3 = L.copy(); L3.loc[L3.arm.isin(["B-MCD-N", "R-MCD-F", "B-LW-F"]), "f1"] = 0.25
    sp = {a: (0.05, 0.01, 0.0) for a in ("B-MCD-N", "R-MCD-F", "B-LW-F")}
    assert RD.select_arm(L3, bt(sp))[0] == "B-LW-F", RD.select_arm(L3, bt(sp))      # ties: F before N, then LW, then R
    T = pd.DataFrame(dict(seg_min=[5, 10, 20, 30], f1=[0.10, 0.19, 0.20, 0.21], sens=[0.5, 0.79, 0.80, 0.81]))
    assert RD.min_length(T, 0.20, 0.81, [5, 10, 20, 30])[0] == 10
    assert RD.min_length(T, 0.30, 0.81, [5, 10, 20, 30])[0] == 30
    print("U1 PASS: selection rule and minimum-length rule on hand-made tables")
    import m2l_core as M
    for n, sz, L_ in ((300, [(100, 160), (590, 640)], 5), (1000, [(0, 30), (1196, 1300)], 10), (77, [], 5)):
        cuts = M.segment_cuts(n, sz, L_)
        assert cuts[0][0] == 0 and cuts[-1][1] == n and all(a < b for a, b in cuts)
        assert all(cuts[i][1] == cuts[i + 1][0] for i in range(len(cuts) - 1))
        for s0, s1 in sz:
            w0, w1 = s0 // 4, -(-s1 // 4)
            assert not any(w0 < b < w1 for _, b in cuts), (cuts, s0, s1)
    ctx = M.onefile_ctx(100, np.ones(100, bool))
    top, st, _ = M.detect(ctx, np.random.default_rng(0).normal(size=100), 0.0, 0.0, 0.02)
    assert top == 0.0 and all(not v.get(0) for v in st.values())
    rng = np.random.default_rng(1)
    X = rng.normal(0, 2e-5, (18, 10_000))
    cc = np.full(18, 1.5)
    mu, sd = M.stats_of(X, "R")
    assert np.allclose(mu, X.mean(1)) and np.allclose(sd, X.std(1, ddof=1))
    mu, sd = M.stats_of(X, "B", cc)
    q75, q25 = np.quantile(X, [0.75, 0.25], axis=1)
    assert np.allclose(mu, np.median(X, 1)) and np.allclose(sd, (q75 - q25) / 1.349 * 1.5)
    assert np.all(np.abs(sd / 1.5 / X.std(1, ddof=1) - 1) < 0.03)
    from sklearn.covariance import MinCovDet
    Z = rng.standard_t(4, size=(300, 2, 16))
    d = M.distances(Z, "MCD")
    assert np.allclose(d[:, 1], MinCovDet(support_fraction=0.75, random_state=0).fit(Z[:, 1]).mahalanobis(Z[:, 1]))
    print("U2 PASS: segment cuts, top = 0, statistics R / B, MCD distances")


P3_SCRIPT = r'''
# P3: the V5 chain on the x1_external .npz of PN01 at k_sel = the L3-eval rows of R-LW-F (one recording)
import json, os, sys
from pathlib import Path
import numpy as np, pandas as pd
if __name__ == "__main__":
    sys.path.insert(0, os.environ["THESIS_REPO"] + "/src")
    import m2l_core as M
    R1 = M.R1
    p, out, k = Path(sys.argv[1]), Path(sys.argv[2]), float(sys.argv[3])
    z = dict(np.load(p, allow_pickle=True)); z.pop("meta")
    idx, D = R1.X1.model_outputs(z)
    ctx = R1.X1.make_ctx(z, idx, D)
    pctx = M.patient_ctx(dict(is_ictal=z["is_ictal"], is_signal_loss=z["is_signal_loss"], file_idx=z["file_idx"],
                              is_buffer=np.zeros(len(z["is_ictal"]), bool)))
    rows, errs = [], []
    for tag in M.TAGS:
        x, smm = M.series(ctx, tag)
        q = M.P3L.q_of(smm, k)
        top, st, pr = M.detect(ctx, x, q, 0.005, M.P3C.CAP)
        M.score_rows(pctx, "PN01", tag, "R-LW-F", top, st, pr, rows, errs)
    pd.DataFrame(rows).to_csv(out, index=False)
    print("P3 rows", len(rows))
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default="/tmp/m2l_synth")
    ap.add_argument("--skip-neg", action="store_true")
    ap.add_argument("--neg-only", action="store_true", help="reuse a world built by an earlier full run")
    a = ap.parse_args()
    t0 = time.time()
    root = Path(a.root)
    if a.neg_only:
        negatives(root, root / "repo", root / "notebooks")
        print(f"ALL PASS (negatives) in {time.time() - t0:.0f} s")
        return
    phys, raw, lap, repo, sp = D.build_world(root)
    for rel in ("results/r2/r0_data/rb1c/channels.csv",):
        (repo / rel).parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(ROOT / rel, repo / rel)
    f1, f3 = root / "input" / "v9-x3-fold1" / "fold1", root / "input" / "v9-x3-fold3" / "fold3"
    f1.mkdir(parents=True)
    f3.mkdir(parents=True)
    for n, txt in (("record.py", T9.RECORD), ("models.py", T9.MODELS), ("record_gen.py", D.RECORD_GEN_EXT),
                   ("runner.py", RR.RUNNER), ("ext_build.py", D.EXT_BUILD), ("p3.py", P3_SCRIPT)):
        (root / n).write_text(txt)
    RR.run(root / "record.py", {}, [repo, lap / "", f1, f3, ",".join(T9.CASES)])
    comp = root / "complete_view"
    (comp / "chbmit").mkdir(parents=True)
    shutil.copytree(phys / "chb24", comp / "chbmit" / "chb24")
    shutil.copytree(sp, comp / "siena")
    dx = root / "input" / "thesis-r2-external-features" / "thesis-r2-external-features"
    RR.run(root / "ext_build.py", dict(R2_TEST="1", THESIS_REPO=str(repo)), [repo, comp, dx, "chb24,PN00,PN01"])
    for p in dx.glob("_*.log"):
        p.unlink()
    RR.run(root / "models.py", {}, [repo, f1, f3, root / "tmp_models"])
    genv = dict(THESIS_REPO=str(repo), R2_WORK=str(root / "work_gen"), R2_INPUT=str(root / "input"),
                R2_SCRATCH=str(root / "scratch_gen"), R2_TEST="1", R1_SRC=str(repo / "src"), OMP_NUM_THREADS="1")
    print(RR.run(root / "record_gen.py", genv).strip().splitlines()[-1])
    print(f"world ready ({time.time() - t0:.0f} s)", flush=True)
    unit_tests(repo)
    nbd = notebooks(root, repo)

    # ---- P1: L2 notebooks
    for nb, tag, run in (("M2L_L2_REC", "l2_rec", "rec"), ("M2L_L2_ROB", "l2_rob", "rob")):
        t = time.time()
        out = RR.run(root / "runner.py", env_for(root, repo, run), [nbd / f"{nb}.ipynb"])
        g = gates(root / f"work_{run}", tag)
        need = ["G-raw", "G-data", "G-stats1", "G-feat1", "G-worker[smoke]", "R1.0-dev", "G-k", "G-chain", "G-split",
                "PROJ", "G-worker[build]", "G-struct[dev]", "G-worker[score_dev]"] + (["G-c"] if run == "rob" else [])
        assert all(g.get(n) == "PASS" for n in need), (nb, g)
        R = pd.read_csv(root / f"work_{run}" / "m2l" / tag / "per_subject.csv")
        assert len(R) == len(T9.DEV) * 4 * 6 * 3 and R.subject.nunique() == len(T9.DEV), (nb, len(R))
        copy_out(root, run, repo, tag)
        print(f"P1 PASS {nb}: every gate, {len(R)} rows, no .npz / EDF ({time.time() - t:.0f} s)", flush=True)

    # ---- R2: reader --l2
    renv = dict(THESIS_REPO=str(repo))
    o = RR.run(repo / "src" / "m2l_read.py", renv, ["--l2"])
    sel = json.loads((repo / "results" / "m2l" / "l2" / "selection.json").read_text())
    assert (repo / "results" / "m2l" / "l2" / "T_L2.md").exists() and sel["arm"] in [x for x in sel["candidates"]] + ["R-LW-F"]
    print("R2 PASS:", o.strip().splitlines()[-1])
    # P2 / P3 need the record scale and LedoitWolf: the L3 runs of this test use R-LW-F (the selection file is
    # overwritten for the test; the reader's own choice was checked above)
    k_rlw = json.loads((repo / "results" / "m2l" / "l2_rec" / "k.json").read_text())["k"]["LW"]
    forced = dict(sel, arm="R-LW-F", S="R", cov="LW", floor="F", k=k_rlw, note="forced in the synthetic test (P2, P3)")
    (repo / "results" / "m2l" / "l2" / "selection.json").write_text(json.dumps(forced, indent=1))

    # ---- P4: L3-short and its reader
    for nb, tag, run, segs in (("M2L_L3_SHORT_A", "l3short_a", "sa", "2,3"), ("M2L_L3_SHORT_B", "l3short_b", "sb", "4,5")):
        t = time.time()
        RR.run(root / "runner.py", env_for(root, repo, run, M2L_TEST_SEGS=segs), [nbd / f"{nb}.ipynb"])
        g = gates(root / f"work_{run}", tag)
        assert all(g.get(n) == "PASS" for n in ("G-sel", "G-raw", "G-data", "R1.0-dev", "G-struct[seg]",
                                                "G-worker[build]")), (nb, g)
        copy_out(root, run, repo, tag)
        print(f"P4 PASS {nb} ({time.time() - t:.0f} s)", flush=True)
    o = RR.run(repo / "src" / "m2l_read.py", dict(renv, M2L_SEG_LIST="2,3,4,5"), ["--l3short"])
    ml = json.loads((repo / "results" / "m2l" / "l3short" / "minlen.json").read_text())
    assert ml["minutes"] in (2, 3, 4, 5, 30)
    print("P4 PASS reader --l3short:", o.strip().splitlines()[-1])
    ml["minutes"], ml["windows"] = 5, 75                       # the test's L3-eval: Siena / chb24 files are 6-7 min
    (repo / "results" / "m2l" / "l3short" / "minlen.json").write_text(json.dumps(ml, indent=1))

    # ---- P4: L3-eval, P2, P3
    t = time.time()
    RR.run(root / "runner.py", env_for(root, repo, "ev"), [nbd / "M2L_L3_EVAL.ipynb"])
    g = gates(root / "work_ev", "l3eval")
    assert all(g.get(n) == "PASS" for n in ("G-sel", "G-raw", "G-data", "R1.0-test", "GE", "G-struct[test]",
                                            "G-struct[ext]", "G-worker[build]")), g
    copy_out(root, "ev", repo, "l3eval")
    o = RR.run(repo / "src" / "m2l_read.py", renv, ["--l3"])
    assert (repo / "results" / "m2l" / "l3" / "T_L3.md").exists()
    print(f"P4 PASS L3-eval + reader --l3 ({time.time() - t:.0f} s)")
    w = repo / "results" / "m2l" / "l3eval"
    st = pd.read_csv(w / "stats_per_recording.csv")
    st = st[st.case == "PN01"]
    meta = json.loads(str(np.load(next(dx.glob("PN01_lf.npz")), allow_pickle=True)["meta"]))
    rel_m = np.max(np.abs(st.centre_uV.values - np.asarray(meta["labelfree_mean_uV"])) / np.asarray(meta["labelfree_std_uV"]))
    rel_s = np.max(np.abs(st.scale_uV.values / np.asarray(meta["labelfree_std_uV"]) - 1))
    assert rel_m < 1e-9 and rel_s < 1e-9, (rel_m, rel_s)
    print(f"P2 PASS: PN01 per-recording statistics = x1 label-free statistics (mean {rel_m:.1e}, SD {rel_s:.1e})")
    RR.run(root / "p3.py", dict(THESIS_REPO=str(repo), R2_TEST="1"), [next(dx.glob("PN01_lf.npz")), root / "p3.csv", k_rlw])
    mine = pd.read_csv(w / "per_subject.csv")
    mine = mine[(mine.subject == "PN01") & (mine.budget == "R-LW-F")].set_index(["seed", "stage"])
    ref = pd.read_csv(root / "p3.csv").set_index(["seed", "stage"])
    for c_ in ("tp", "fp", "n_ref", "short_tp", "short_n"):
        assert (mine.loc[ref.index, c_].astype(int) == ref[c_].astype(int)).all(), c_
    print("P3 PASS: PN01 rows of the per-recording path = the V5 chain on the x1 .npz at the same k")

    if not a.skip_neg:
        negatives(root, repo, nbd)
    print(f"ALL PASS in {time.time() - t0:.0f} s")


