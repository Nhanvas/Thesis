#!/usr/bin/env python
"""m2l_synthetic_test.py -- end-to-end test of the M2L notebooks and the reader on SYNTHETIC EDF files (build container
only; never on Kaggle, never on real data). Design results/m2l/DESIGN_L2.md §10.

World = the EUR_DIAG test world (src/eur_diag_synthetic_test.py on src/eur_9a_synthetic_test.py: 23 CHB-MIT-like cases
of 2 files, chb12_27-29 without FZ-CZ, gap files absent and one corrupted file on the fake Kaggle copy -> fetched from
the fake PhysioNet; chb24 and Siena PN00 / PN01; earlier .npz, external .npz, random GAE checkpoints and the record rows
GENERATED by the record code), with files of 6 min (90 windows, above the L2 guard of 76) and Siena / chb24 files of 6–7 min.
Checks
  U1  reader rules on hand-made tables: selection (none -> P0; a candidate; the sensitivity guard; ties -> F, LW, R) and
      minimum length (smallest qualifying; none -> 30)
  U2  m2l_core units: segment cuts never split a seizure and cover the recording; top = 0 -> no event; R / B statistics
      = an independent computation; MCD distance = an independent MinCovDet call
  P1  M2L_L2_REC and M2L_L2_ROB: every gate PASS; rows complete; no .npz / EDF in the outputs
  R2  reader --l2: A0 / A1 PASS, selection.json written by the rule
  P2  (non-circular) PN01 has ONE recording: its per-recording record statistics (L3-eval, arm forced to R-LW-F for this
      check) = the label-free patient statistics of the external .npz built by x1_external (relative 1e-9)
  P3  (non-circular) PN01: the L3-eval rows of R-LW-F = the V5 chain run here on the x1_external .npz at the same k
  P4  M2L_L3_SHORT_A / _B (segments 2, 3 / 4, 5 min in this world) and reader --l3short; M2L_L3_EVAL and reader --l3
  NEG1 rb1c channels.csv edited -> STOP at G-c (L2_ROB)        NEG2 committed chb08 statistics +0.1 % -> STOP at G-feat1
  NEG3 M2L_TEST_CHAIN_SHIFT (k x 1.05 inside G-chain) -> STOP at G-chain
  NEG4 is_buffer flipped in an earlier .npz (not scored, R1.0 passes) -> STOP at G-struct[dev]
  NEG5 selection.json removed -> STOP at G-sel (L3-short)       NEG6 an edited module -> STOP before the run
  python src/m2l_synthetic_test.py [--root DIR] [--skip-neg]
"""
