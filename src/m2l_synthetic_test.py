        c.loc[c.case.isin(["chb01", "chb02", "chb04", "chb05", "chb07", "chb08", "chb09"]) & (c.channel == "FP1-F7"),
              "sd_record_uV"] *= 1.5
        c.to_csv(f, index=False)
        RR.run(root / "runner.py", env_for(root, cp, "neg1"), [nbd / "M2L_L2_ROB.ipynb"], expect_fail="G-c FAIL")
        print("NEG1 PASS: edited RB1c constants stop at G-c")
