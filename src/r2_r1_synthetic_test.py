# ============================================================================ synthetic data
def make_case(c, seed, n_files=3, extra=False, kind="chb"):
    rng = np.random.default_rng(seed)
    wpf = [int(rng.integers(120, 160)) for _ in range(n_files)] + ([60] if extra else [])
    names = [f"{c}_{i + 1:02d}.edf" if kind == "chb" else f"{c}-{i + 1}.edf" for i in range(n_files)]
    if extra:
        names.append(f"{c}_{n_files + 1:02d}.edf")
    n = sum(wpf)
    fidx = np.concatenate([np.full(w, i, np.int16) for i, w in enumerate(wpf)])
    ict = np.zeros(n, bool); buf = np.zeros(n, bool); sl = np.zeros(n, bool)
    off = 0
    for i, w in enumerate(wpf[:n_files]):
        if i in (0, 2):
            L = int(rng.integers(6, 16)); a = off + int(rng.integers(25, w - L - 30))
            ict[a:a + L] = True
            buf[a + L:min(off + w, a + L + 40)] = True
        off += w
    if c in ("chb17", "chb04", "PN01"):
        a = wpf[0] + 50
        sl[a:a + 4] = True
    fl5 = (rng.random(n) < 0.08) | (ict & (rng.random(n) < 0.8))
    adj = rng.random((n, 18, 18)).astype(np.float32)
    adj = (adj + adj.transpose(0, 2, 1)) / 2
    adj[:, np.arange(18), np.arange(18)] = 0
    thr = np.quantile(adj.reshape(n, -1), 0.8, axis=1)[:, None, None]
    adj = np.where(adj >= thr, adj, 0).astype(np.float32)
    bp5 = np.exp(rng.normal(-5, 1, (n, 18, 5))).astype(np.float32)
    f7 = (F7_MU + F7_SD * rng.normal(0, 1, (n, 18, 7))).astype(np.float32)
    bp5[ict] *= 3.0
    f7[ict, :8] += 1.5
    adj[ict] *= 1.5
    f7[np.flatnonzero(sl)[:1], 3, 6] = np.nan                        # an undefined cell inside signal loss (chb17-like)
    z = dict(adj=adj, bp5=bp5, f7=f7, is_ictal=ict, is_buffer=buf, is_flag5sd=fl5, is_signal_loss=sl, file_idx=fidx,
             files=np.array(names, dtype=object))
    if kind == "chb":
        z["zgamma_raw"] = rng.normal(0, 1, n).astype(np.float32)
        if c != "chb07":
            z["skipped_files"] = np.array([], dtype=object)
    return z, wpf


def stats_of(c, z, seed, scale=1.0):
    rng = np.random.default_rng(seed + 7)
    sd = (rng.uniform(20, 60, 18) * scale).tolist()
    ict = np.asarray(z["is_ictal"])
    return dict(subject_id=c, n_interictal=int((~ict).sum()), n_ictal=int(ict.sum()), n_rejected=int(z["is_flag5sd"].sum()),
                ratio=round(float((~ict).sum()) / max(1, int(ict.sum())), 1), ch_mean_uV=rng.normal(0, 1, 18).tolist(),
                ch_std_uV=sd, artifact_thresh_uV=[5 * s for s in sd], r2=dict(build="synthetic"))


def rebuilt(z, seed):
    """what R0 wrote for a gap-free case: the same windows, flags and files, f7 / bp5 at the float level of a rebuild on
    another machine, ~0.04 % of adjacency entries flipped by the top-k cut, and skipped_files always present (every c1b
    build writes it; only the record's chb07 lacks it)."""
    rng = np.random.default_rng(seed)
    zn = {k: np.array(v, copy=True) for k, v in z.items()}
    ok = ~zn["is_signal_loss"]
    zn["f7"][ok] = (zn["f7"][ok].astype(np.float64) + rng.normal(0, 2e-7, zn["f7"][ok].shape)).astype(np.float32)
    zn["bp5"][ok] = (zn["bp5"][ok] * (1 + rng.normal(0, 1e-7, zn["bp5"][ok].shape))).astype(np.float32)
    flip = rng.random(zn["adj"].shape) < 4e-4
    zn["adj"][flip] = np.where(zn["adj"][flip] > 0, 0.0, 0.05).astype(np.float32)
    zn.setdefault("skipped_files", np.array([], dtype=object))
    return zn


def clean(z):
    return ~z["is_ictal"] & ~z["is_buffer"] & ~z["is_signal_loss"] & ~z["is_flag5sd"]


def build_world(root):
    if root.exists():
        shutil.rmtree(root)
    repo, inp = root / "repo", root / "input" / "datasets" / "u"
    shutil.copytree(ROOT / "src", repo / "src", ignore=shutil.ignore_patterns("__pycache__"))
    for rel in ("results/v9_x3/fold_manifests.json", "results/p3c_freeze/freeze.json", "results/p3_levers/calibration.json"):
        (repo / rel).parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(ROOT / rel, repo / rel)
    f1, f3 = inp / "v9-x3-fold1" / "fold1", inp / "v9-x3-fold3" / "fold3"
    ds = inp / "thesis-r2-chbmit-features" / "thesis-r2-chbmit-features"
    prov = inp / "thesis-r2-chbmit-features" / "r2" / "r0_data" / "chb" / "stats_earlier"
    dx = inp / "thesis-r2-external-features" / "thesis-r2-external-features"
    r0 = repo / "results" / "r2" / "r0_data"
    for d in (f1, f3, ds, prov, dx, r0 / "chb" / "stats_earlier", r0 / "ext"):
        d.mkdir(parents=True, exist_ok=True)
    diff, inv, earlier_z = {}, [], {}
    for i, c in enumerate(CHB):
        z, wpf = make_case(c, 100 + i)
        earlier_z[c] = z
        dst = (f1 if i % 2 else f3) / f"{c}.npz"
        np.savez(dst, **z)
        st = stats_of(c, z, 100 + i)
        (r0 / "chb" / "stats_earlier" / f"{c}_stats.json").write_text(json.dumps(st, indent=1))
        (prov / f"{c}_stats.json").write_text(json.dumps(st, indent=1))
        h_e = len(z["is_ictal"]) * 4 / 3600
        if c in GAP:
            zn, _ = make_case(c, 100 + i, extra=True)
            stn = stats_of(c, zn, 100 + i, scale=1.03)
            stn["ch_mean_uV"] = (np.asarray(st["ch_mean_uV"]) + 0.01).tolist()
            np.savez(ds / f"{c}.npz", **zn)
            (ds / f"{c}_stats.json").write_text(json.dumps(stn, indent=1))
            sdo, sdn = np.asarray(st["ch_std_uV"]), np.asarray(stn["ch_std_uV"])
            rel = {"ch_mean_uV (change / earlier SD)": (np.asarray(stn["ch_mean_uV"]) - np.asarray(st["ch_mean_uV"])) / sdo,
                   "ch_std_uV (relative change)": (sdn - sdo) / sdo,
                   "artifact_thresh_uV (relative change)": (np.asarray(stn["artifact_thresh_uV"])
                                                            - np.asarray(st["artifact_thresh_uV"])) / np.asarray(st["artifact_thresh_uV"])}
            diff[c] = dict(windows_earlier=int(len(z["is_ictal"])), windows_complete=int(len(zn["is_ictal"])),
                           ictal_windows=[int(z["is_ictal"].sum()), int(zn["is_ictal"].sum())],
                           clean_windows=[int(clean(z).sum()), int(clean(zn).sum())],
                           flag5sd_windows=[int(z["is_flag5sd"].sum()), int(zn["is_flag5sd"].sum())],
                           counts_earlier={k: st[k] for k in ("n_interictal", "n_ictal", "n_rejected")},
                           counts_complete={k: stn[k] for k in ("n_interictal", "n_ictal", "n_rejected")},
                           stats_rel_change={k: dict(per_channel=v.tolist()) for k, v in rel.items()})
            h_n = len(zn["is_ictal"]) * 4 / 3600
        else:
            zn = rebuilt(z, 300 + i)
            np.savez(ds / f"{c}.npz", **zn)
            (ds / f"{c}_stats.json").write_text(json.dumps(st, indent=1))
            h_n = h_e
        inv.append(dict(db="chbmit", case=c, hours_used_windows=h_n, earlier_hours_used_windows=h_e))
    (r0 / "chb" / "diff_chb11_chb21.json").write_text(json.dumps(diff, indent=1))
    import pandas as pd
    pd.DataFrame(inv).to_csv(r0 / "chb" / "inventory_cases.csv", index=False)
    pd.DataFrame(inv).to_csv(ds / "inventory.csv", index=False)
    ext_rows = []
    for j, c in enumerate(EXT):
        z, wpf = make_case(c, 500 + j, n_files=2 if c != "PN00" else 3, kind="chb" if c == "chb24" else "siena")
        z = {k: z[k] for k in ("adj", "bp5", "f7", "is_ictal", "is_signal_loss", "file_idx", "files")}
        h = len(z["is_ictal"]) * 4 / 3600
        meta = dict(kind="chb" if c == "chb24" else "siena", notch=60.0 if c == "chb24" else 50.0, summary="synthetic",
                    listed=len(wpf), present=len(wpf), skipped=[], hours=h)
        np.savez(dx / f"{c}_lf.npz", **z, meta=json.dumps(meta))
        ext_rows.append(dict(case=c, scored=True, files=len(wpf), windows=len(z["is_ictal"]), hours=h,
                             ictal_windows=int(z["is_ictal"].sum()), signal_loss_windows=int(z["is_signal_loss"].sum()),
                             skipped=0))
    pd.DataFrame(ext_rows).to_csv(r0 / "ext" / "external_cases.csv", index=False)
    x1 = repo / "results" / "x1_external"
    x1.mkdir(parents=True, exist_ok=True)
    for c in EXT:                                           # placeholders: r2_r1.EXT is read from these names at import
        (x1 / f"rows_{c}.csv").write_text("placeholder\n")
    # fake committed checkpoints: random GAE v2, the record json format, constants from the synthetic earlier windows
    import torch
    sys.path[:0] = [str(repo / "src" / "retrain"), str(repo / "src")]
    import gae_joint as G
    import train_gae_v2 as TGV2
    tmp = root / "tmp_earlier"
    tmp.mkdir()
    for c in CHB:
        np.savez(tmp / f"{c}.npz", **earlier_z[c])
    mu, sd = TGV2.norm_constants(tmp, "clean")
    md = repo / "data" / "models_v2"
    md.mkdir(parents=True)
    for s in (42, 1, 2, 3):
        torch.manual_seed(s)
        m = G.GAEModel(in_dim=30, bands=12)
        torch.save(m.state_dict(), md / f"gae_v2_clean_seed{s}.pt")
        (md / f"gae_v2_clean_seed{s}.json").write_text(json.dumps(dict(
            variant="clean", seed=s, in_dim=30, out_x=12, n_add=7, add_mean=mu.tolist(), add_std=sd.tolist(), clip=4.0,
            n_train={c: int(clean(earlier_z[c]).sum()) for c in TRAIN}, n_val={c: int(clean(earlier_z[c]).sum()) for c in VAL},
            epochs=200, batch=32, lr=0.001, lambda_=0.1), indent=1))
    shutil.rmtree(tmp)
    return repo, root / "input"


