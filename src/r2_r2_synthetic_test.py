#!/usr/bin/env python
"""r2_r2_synthetic_test.py -- end-to-end test of the stage R2 notebooks (R2_SMOKE, R2_A, R2_B, R2_C) and the R2 aggregate
on SYNTHETIC feature files (build container only; never on Kaggle, never on real data).

World (under --root): repo/ = a copy of src/ + the real results/v9_x3/fold_manifests.json, folds.json and
results/f1_repcv/partitions.json (24 real case names, the real folds); fake committed models (4 random GAE fold models with
constants from the synthetic earlier windows, 4 random MLP-AE and 4 random CNN checkpoints); a fake R0 diff report and a
fake R1_SMOKE data_sha256.csv; the record result files (results/v9_x3 fold rows + calibration, gae_cv_seizures.csv,
results/model_cmp per_subject / seizures / raw/ + the closed aggregate's tables, gates_all.json, part1_descriptors.csv)
are GENERATED by this module's own code paths on the earlier data (record_gen.py), so R2.0 here tests the mechanics, not
the equivalence with the record: that is R2.0 on Kaggle. input/ = v9-x3-fold1/3 (earlier .npz, 24 cases) and
thesis-r2-chbmit-features (gap-free cases with the SAME feature arrays + skipped_files; chb11 / chb21 with one added
seizure-free file).
Non-circular checks:
  N1  the counterfactual path on the NEW view with the committed GAE reproduces the generated record rows exactly on fold
      4 (its training cases are gap-free, so its k and its gap-free held-out rows must not move);
  N2  patched_meta: inside, model_cmp_core.fold_meta(f) = the new fold meta and node_input uses its constants; outside,
      the committed meta again;
  N3  G-vec and G-mlp inside the notebooks (the f1_core gates on synthetic windows).
Runs: R2_SMOKE PASS (all gates, R2.0 exact / within tolerance, smoke jobs, projection); negative paths: one record IF row
tp + 1 -> STOP R2.0-if; one MLP record row fp + 3 -> STOP R2.0-mlp (fp + 2 passes); a pinned hash changed -> STOP
G-data; a record n_ref changed -> STOP D0'. R2_A, R2_B, R2_C (epochs reduced by R2_TEST_EPOCHS in test mode only) PASS;
R2_A resumed with its output attached reuses all 8 jobs (byte-identical rows); the aggregate (src/r2_r2_aggregate.py) on
the three outputs: A1 PASS, the closed analyses A-F run, every table written; A0 on the REAL record files of this clone PASS.
  python src/r2_r2_synthetic_test.py [--root DIR]
"""
import argparse
import json
import os
import shutil
import subprocess
import sys
import time
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from r2_r1_synthetic_test import RUNNER, clean, make_case, run   # noqa: E402  (shared synthetic helpers)

CHB = [f"chb{i:02d}" for i in range(1, 25)]
GAP = ("chb11", "chb21")


def build_world(root):
    if root.exists():
        shutil.rmtree(root)
    repo, inp = root / "repo", root / "input" / "datasets" / "u"
    shutil.copytree(ROOT / "src", repo / "src", ignore=shutil.ignore_patterns("__pycache__"))
    for rel in ("results/v9_x3/fold_manifests.json", "results/v9_x3/folds.json", "results/f1_repcv/partitions.json"):
        (repo / rel).parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(ROOT / rel, repo / rel)
    f1, f3 = inp / "v9-x3-fold1" / "fold1", inp / "v9-x3-fold3" / "fold3"
    ds = inp / "thesis-r2-chbmit-features" / "thesis-r2-chbmit-features"
    for d in (f1, f3, ds, repo / "results" / "r2" / "r0_data" / "chb", repo / "results" / "r2" / "r1_system" / "smoke"):
        d.mkdir(parents=True, exist_ok=True)
    diff, pin = {}, []
    import hashlib
    for i, c in enumerate(CHB):
        z, _ = make_case(c, 100 + i)
        np.savez((f1 if i % 2 else f3) / f"{c}.npz", **z)
        if c in GAP:
            zn, _ = make_case(c, 100 + i, extra=True)
            zn.setdefault("skipped_files", np.array([], dtype=object))
            names = [str(x) for x in zn["files"]]
            diff[c] = dict(files_added=[names[-1]], windows_earlier=int(len(z["is_ictal"])),
                           windows_complete=int(len(zn["is_ictal"])),
                           ictal_windows=[int(z["is_ictal"].sum()), int(zn["is_ictal"].sum())],
                           clean_windows=[int(clean(z).sum()), int(clean(zn).sum())])
        else:
            zn = dict(z)
            zn.setdefault("skipped_files", np.array([], dtype=object))
        np.savez(ds / f"{c}.npz", **zn)
        pin.append(dict(dataset="thesis-r2-chbmit-features", file=f"{c}.npz",
                        sha256=hashlib.sha256((ds / f"{c}.npz").read_bytes()).hexdigest()))
    (repo / "results" / "r2" / "r0_data" / "chb" / "diff_chb11_chb21.json").write_text(json.dumps(diff, indent=1))
    import pandas as pd
    pd.DataFrame(pin).to_csv(repo / "results" / "r2" / "r1_system" / "smoke" / "data_sha256.csv", index=False)
    return repo, root / "input"


RECORD_GEN = r'''
# record_gen.py: fake committed models + the record files, generated by r2_r2's own code paths on the earlier data
import json, os, shutil, sys, time
from pathlib import Path
import numpy as np, pandas as pd, torch
REPO = Path(os.environ["THESIS_REPO"])
sys.path.insert(0, str(REPO / "src"))
import r2_r2 as R2
F, C = R2.F, R2.C
R2.STATE["tag"] = "gen"
R2.build_views()
R2.use_view("earlier")
X3, MC = REPO / "results" / "v9_x3", REPO / "results" / "model_cmp"
counts = {s: int(C.clean_mask(C.npz(s)).sum()) for s in C.ALL}
for f in C.FOLDS:
    tr = sorted(C.MAN[str(f)]["train_cases"])
    mu, sd = F.fold_constants(tr)
    d = X3 / "models" / f"fold{f}"; d.mkdir(parents=True, exist_ok=True)
    torch.manual_seed(f)
    torch.save(F.build("gae").state_dict(), d / f"gae_fold{f}_seed42.pt")
    (d / f"gae_fold{f}_seed42.json").write_text(json.dumps(dict(fold=f, seed=42, in_dim=30, out_x=12, clip=4.0,
        add_mean=mu.tolist(), add_std=sd.tolist(), n_train={s: counts[s] for s in tr}), indent=1))
(MC / "ckpt").mkdir(parents=True, exist_ok=True)
for f in C.FOLDS:
    torch.manual_seed(10 + f); torch.save(C.build_mlp_ae().state_dict(), MC / "ckpt" / f"mlp_fold{f}.pt")
    torch.manual_seed(20 + f); torch.save(C.build_cnn().state_dict(), MC / "ckpt" / f"cnn_fold{f}.pt")
jd = R2.out_dir() / "gen"
def go(spec):
    r = R2.job(dict(spec, stage="gen"))
    assert r["status"] == "done", r
    p = R2.out_dir() / "gen" / spec["name"]
    return {n: pd.read_csv(p / f"{n}.csv") for n in ("per_subject", "curves", "auroc", "seizures")}, r
# v9_x3 record (GAE fold models, own point) + gae_cv_seizures
G = {}
for f in C.FOLDS:
    G[f], r = go(dict(name=f"gae_f{f}", kind="cf", model="gae", fold=f, view="earlier"))
    own = G[f]["per_subject"][G[f]["per_subject"].point == "own"].assign(seed=42)
    own[["fold", "seed", "subject", "stage", "tp", "fp", "n_ref", "nonict_h", "short_tp", "short_n", "top", "q_raw"]].to_csv(
        X3 / f"fold{f}_seed42_per_subject.csv", index=False)
    (X3 / f"fold{f}_seed42_calibration.json").write_text(json.dumps(dict(k=float(own.k.iloc[0]))))
hard = REPO / "results" / "v9_final" / "hard"; hard.mkdir(parents=True, exist_ok=True)
pd.concat([G[f]["seizures"] for f in C.FOLDS])[["subject", "file", "onset_s", "duration_s", "caught"]].to_csv(
    hard / "gae_cv_seizures.csv", index=False)
# model_cmp record: raw/A2 (gae, if, hgb, svm), raw/B (cnn), raw/M12 + raw/M34 (mlp)
raw = {k: {n: [] for n in ("per_subject", "curves", "auroc", "seizures")} for k in ("A2", "B", "M12", "M34")}
jobs = {k: [] for k in raw}
def add(nb, T, model, fold, sec):
    for n in raw[nb]:
        raw[nb][n].append(T[n])
    jobs[nb].append(dict(model=model, fold=fold, status="done", seconds=sec))
for f in C.FOLDS:
    add("A2", G[f], "gae", f, 60)
T, r = go(dict(name="if", kind="iforest", model="if", view="earlier"))
for f in C.FOLDS:
    add("A2", {n: (v[v.fold == f] if "fold" in v.columns else v) for n, v in T.items()}, "if", f, 30)
for m in ("hgb", "svm"):
    for f in C.FOLDS:
        T, r = go(dict(name=f"{m}_f{f}", kind="sup", model=m, fold=f, view="earlier"))
        add("A2", T, m, f, 300 if m == "hgb" else 3600 * (1 + f / 4))
        (MC / "raw" / "A2").mkdir(parents=True, exist_ok=True)
        (MC / "raw" / "A2" / f"fit_{m}_fold{f}.json").write_text(json.dumps(dict(model=m, fold=f, n_train=int(r["n_train"]))))
for f in C.FOLDS:
    T, r = go(dict(name=f"cnn_f{f}", kind="cf", model="cnn", fold=f, view="earlier")); add("B", T, "cnn", f, 150)
    T, r = go(dict(name=f"mlp_f{f}", kind="cf", model="mlp", fold=f, view="earlier")); add("M12" if f <= 2 else "M34", T, "mlp", f, 4000)
for nb in raw:
    d = MC / "raw" / nb; d.mkdir(parents=True, exist_ok=True)
    for n, L in raw[nb].items():
        pd.concat(L, ignore_index=True).to_csv(d / f"{n}.csv", index=False)
    (d / "gates.json").write_text(json.dumps([dict(gate="D0", status="PASS")]))
    (d / "run_meta.json").write_text(json.dumps(dict(notebook=nb)))
    (d / "jobs.json").write_text(json.dumps(jobs[nb]))
S = pd.read_csv(MC / "raw" / "A2" / "seizures.csv")
desc = S[S.model == "gae"][["subject", "file", "onset_s", "duration_s", "caught"]].assign(set="development", amp_ratio=1.5)
(REPO / "results" / "v9_v1").mkdir(parents=True, exist_ok=True)
desc.to_csv(REPO / "results" / "v9_v1" / "part1_descriptors.csv", index=False)
import subprocess
subprocess.check_call([sys.executable, str(REPO / "src" / "model_cmp_aggregate.py"), str(MC / "raw"), "--out", str(MC)],
                      stdout=subprocess.DEVNULL)
print("record generated:", sorted(p.name for p in MC.iterdir()))
'''

CHECK_N = r'''
# check_n.py: N1 (counterfactual on the new view = record on fold 4) and N2 (patched_meta)
import json, os, sys
from pathlib import Path
import numpy as np, pandas as pd
REPO = Path(os.environ["THESIS_REPO"])
sys.path.insert(0, str(REPO / "src"))
import r2_r2 as R2
C = R2.C
R2.STATE["tag"] = "check"
R2.build_views()
R2.use_view("new")
M = R2.new_metas()
assert C.fold_meta(2)["add_mean"] == json.loads((C.X3 / "models/fold2/gae_fold2_seed42.json").read_text())["add_mean"]
with R2.patched_meta(M):
    assert C.fold_meta(2) is M[2]
    z = C.npz("chb03"); idx = np.arange(10)
    X, *_ = C.node_input(z, idx, C.fold_meta(2))
    f7 = z["f7"][idx].astype(np.float64)
    fz = (f7 - np.array(M[2]["add_mean"])) / np.array(M[2]["add_std"])
    fa = (np.clip(fz, -4, 4) + 4) / 8
    assert np.allclose(X[:, :, 23:], np.nan_to_num(fa.astype(np.float32)), atol=1e-6)
assert C.fold_meta(2)["add_mean"] != M[2]["add_mean"]
print("N2: patched_meta in force inside (node_input uses the new constants), committed meta restored outside")
r = R2.job(dict(stage="check", name="cf_gae_f4", kind="cf", model="gae", fold=4, view="new"))
assert r["status"] == "done", r
mine = pd.read_csv(R2.out_dir() / "check" / "cf_gae_f4" / "per_subject.csv")
ref = pd.read_csv(C.X3 / "fold4_seed42_per_subject.csv")
k_ref = json.loads((C.X3 / "fold4_seed42_calibration.json").read_text())["k"]
assert abs(r["k"] - k_ref) <= 1e-12 * abs(k_ref), (r["k"], k_ref)
mg = mine[mine.point == "own"].merge(ref, on=["subject", "stage"], suffixes=("", "_ref"))
free = mg[~mg.subject.isin(R2.GAP)]
assert len(free) == 2 * 5 and (free.tp == free.tp_ref).all() and (free.fp == free.fp_ref).all(), free
gap = mg[mg.subject.isin(R2.GAP)]
assert len(gap) == 4 and (gap.nonict_h > gap.nonict_h_ref).all(), gap
print("N1: committed GAE on the new view = record on fold 4 (k equal, 5 gap-free held-out cases exact); chb11 / chb21 "
      "have more non-ictal hours")
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default="/tmp/r2_r2_synth")
    a = ap.parse_args()
    t0 = time.time()
    root = Path(a.root)
    repo, inp = build_world(root)
    # A0 of the aggregate on the REAL record files of this clone
    p = subprocess.run([sys.executable, str(ROOT / "src" / "r2_r2_aggregate.py"), "--a0-only"], capture_output=True, text=True)
    assert p.returncode == 0 and "A0 PASS" in p.stdout, p.stdout + p.stderr
    print("A0 on the real record: PASS")
    for name, body in (("record_gen.py", RECORD_GEN), ("check_n.py", CHECK_N), ("runner.py", RUNNER)):
        (root / name).write_text(body)
    base = dict(R2_TEST="1", THESIS_REPO=str(repo), R2_INPUT=str(inp), OMP_NUM_THREADS="1", OPENBLAS_NUM_THREADS="1",
                MKL_NUM_THREADS="1", PYTHONHASHSEED="0", R2_TEST_EPOCHS="2")
    print(run(root / "record_gen.py", dict(base, R2_WORK=str(root / "gen_work"), R2_SCRATCH=str(root / "gen_scratch")))[-400:])
    print(run(root / "check_n.py", dict(base, R2_WORK=str(root / "chk_work"), R2_SCRATCH=str(root / "chk_scratch")))[-600:])
    nbdir = root / "notebooks"
    env_b = dict(os.environ, R2_NB_OUTDIR=str(nbdir))
    subprocess.check_call([sys.executable, str(ROOT / "src" / "r2_r2_make_notebooks.py"), "--smoke", "r2-r2-code",
                           "--runs", "0" * 40], env=env_b)

    def nb_env(tag, extra=None):
        e = dict(R2_TEST_REPO=str(repo), R2_TEST_INPUT=str(inp), R2_TEST_WORK=str(root / f"work_{tag}"),
                 R2_TEST_SCRATCH=str(root / f"scratch_{tag}"), R2_TEST="1", OMP_NUM_THREADS="1", PYTHONHASHSEED="0",
                 R2_TEST_EPOCHS="2")
        e.update(extra or {})
        return e

    def gates(tag, nb):
        return {g["gate"]: g for g in json.loads((root / f"work_{tag}" / "r2" / "r2_cv" / nb / "gates.json").read_text())}

    import pandas as pd
    # --- R2_SMOKE
    print(run(root / "runner.py", nb_env("smoke"), [nbdir / "R2_SMOKE.ipynb"])[-2500:])
    g = gates("smoke", "smoke")
    want = ["G-data", "D0'", "G-const", "G-vec", "G-mlp", "R2.0-gae (GG0)", "R2.0-if", "R2.0-hgb", "R2.0-svm", "R2.0-mlp",
            "R2.0-cnn"]
    assert all(g[w]["status"] == "PASS" for w in want), {w: g.get(w, {}).get("status") for w in want}
    assert g["G-vec"]["exact"] and g["G-mlp"]["exact"], (g["G-vec"], g["G-mlp"])
    for m in ("if", "hgb", "svm", "mlp", "cnn"):
        assert g[f"R2.0-{m}"]["exact_rows"] == g[f"R2.0-{m}"]["rows"] > 0, g[f"R2.0-{m}"]
    sm = root / "work_smoke" / "r2" / "r2_cv" / "smoke"
    for f in ("data_sha256.csv", "d0.json", "projection.json", "fold_constants.csv", "fold_metas_new.json", "SUMMARY.md",
              "smoke/gae_f1/per_subject.csv", "smoke/svm_f1/per_subject.csv", "smoke/cnn_f1/ckpt/cnn_fold1_SMOKE.pt",
              "smoke/cf_gae_f1/per_subject.csv", "r20/r20_summary.json"):
        assert (sm / f).exists(), f
    proj = json.loads((sm / "projection.json").read_text())
    assert set(proj["wall_h"]) == {"R2_A", "R2_B", "R2_C"} and all(proj["fits"].values()), proj["wall_h"]
    print("R2_SMOKE PASS (all gates; R2.0 exact on the synthetic record; smoke jobs; projection)")

    # --- negative paths
    def perturb(rel, fn):
        pth = repo / rel
        keep = pth.read_bytes()
        df = pd.read_csv(pth)
        fn(df)
        df.to_csv(pth, index=False)
        return pth, keep
    sel = lambda d, m: (d.model == m) & (d.index == d[d.model == m].index[3])   # noqa: E731
    pth, keep = perturb("results/model_cmp/per_subject.csv", lambda d: d.__setitem__("tp", d.tp + sel(d, "if")))
    run(root / "runner.py", nb_env("neg_if"), [nbdir / "R2_SMOKE.ipynb"], expect_fail="R2.0-if FAIL")
    pth.write_bytes(keep)
    pth, keep = perturb("results/model_cmp/per_subject.csv", lambda d: d.__setitem__("fp", d.fp + 3 * sel(d, "mlp")))
    run(root / "runner.py", nb_env("neg_mlp"), [nbdir / "R2_SMOKE.ipynb"], expect_fail="R2.0-mlp FAIL")
    pth.write_bytes(keep)
    pin = repo / "results" / "r2" / "r1_system" / "smoke" / "data_sha256.csv"
    keep = pin.read_bytes()
    pv = pd.read_csv(pin); pv.loc[5, "sha256"] = "0" * 64; pv.to_csv(pin, index=False)
    run(root / "runner.py", nb_env("neg_pin"), [nbdir / "R2_SMOKE.ipynb"], expect_fail="G-data FAIL")
    pin.write_bytes(keep)
    pth, keep = perturb("results/v9_x3/fold2_seed42_per_subject.csv", lambda d: d.__setitem__("n_ref", d.n_ref + (d.index < 2)))
    run(root / "runner.py", nb_env("neg_d0"), [nbdir / "R2_SMOKE.ipynb"], expect_fail="D0' FAIL")
    pth.write_bytes(keep)
    print("R2_SMOKE negative paths: R2.0-if (tp + 1), R2.0-mlp (fp + 3), G-data (pinned hash), D0' (n_ref) -> STOP")

    # --- R2_A / R2_B / R2_C, pinned to the smoke's projection (as if committed)
    pd_ = repo / "results" / "r2" / "r2_cv" / "smoke"
    pd_.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(sm / "projection.json", pd_ / "projection.json")
    outs = {}
    for n, tag in (("R2_A", "a"), ("R2_B", "b"), ("R2_C", "c")):
        print(run(root / "runner.py", nb_env(tag), [nbdir / f"{n}.ipynb"])[-1200:])
        outs[tag] = root / f"work_{tag}" / "r2" / "r2_cv" / tag
        assert (outs[tag] / "model_cmp" / "per_subject.csv").exists(), n
    A = pd.read_csv(outs["a"] / "model_cmp" / "per_subject.csv")
    assert set(A.model) == {"gae", "mlp"} and len(A) == 2 * 24 * 4, (set(A.model), len(A))
    Bp = pd.read_csv(outs["b"] / "model_cmp" / "per_subject.csv")
    assert set(Bp.model) == {"if", "hgb", "svm"} and len(Bp) == 3 * 24 * 4
    assert set(pd.read_csv(outs["b"] / "cf" / "per_subject.csv").model) == {"gae", "mlp"}
    assert set(pd.read_csv(outs["c"] / "cf" / "per_subject.csv").model) == {"cnn"}
    js = json.loads((outs["a"] / "jobs" / "gae_f1" / "gae_fold1_seed42.json").read_text())
    assert js["epochs"] == 2 and js["G2"] == "PASS", js
    print("R2_A, R2_B, R2_C PASS (rows complete; counterfactual rows written)")
    # resume R2_A with its output attached
    prev = root / "input" / "datasets" / "u" / "r2-a-v1"
    shutil.copytree(root / "work_a", prev)
    run(root / "runner.py", nb_env("a2"), [nbdir / "R2_A.ipynb"])
    r2a = root / "work_a2" / "r2" / "r2_cv" / "a"
    jobs = json.loads((r2a / "jobs.json").read_text())
    assert len(jobs) == 8 and all(j["status"] == "reused" for j in jobs), jobs
    assert (r2a / "model_cmp" / "per_subject.csv").read_bytes() == (outs["a"] / "model_cmp" / "per_subject.csv").read_bytes()
    shutil.rmtree(prev)
    print("R2_A resumed: 8 jobs reused, merged rows byte-identical")
    # --- the aggregate on the three outputs (A0 on the synthetic record skips the locked-number checks: R2_TEST)
    agg = root / "agg"
    run(repo / "src" / "r2_r2_aggregate.py", dict(R2_TEST="1", THESIS_REPO=str(repo), PYTHONHASHSEED="0"),
        ["--runs", outs["a"], outs["b"], outs["c"], "--out", agg])
    ag = {x["gate"]: x for x in json.loads((agg / "gates.json").read_text())}
    assert ag["A0"]["status"] == "PASS" and ag["A1"]["status"] == "PASS", ag
    for f in ("rows_vs_record.csv", "summary.csv", "bootstrap.csv", "per_subject.csv", "k.csv", "seizures.csv",
              "model_vs_gae.csv", "SUMMARY.md", "model_cmp/summary.csv", "model_cmp/paired_bootstrap.csv",
              "model_cmp/complementarity.csv"):
        assert (agg / f).exists(), f
    Bt = pd.read_csv(agg / "bootstrap.csv")
    assert {"rerun - record", "data (cf - record)", "new models (rerun - cf)"} <= set(Bt.step), set(Bt.step)
    assert set(pd.read_csv(agg / "summary.csv").system) == {"record", "cf", "rerun"}
    print("aggregate on the synthetic runs: A0, A1 PASS; analyses A-F and every table written")
    print(f"ALL PASS ({time.time() - t0:.0f} s)")


if __name__ == "__main__":
    main()
